def markdown_document(lines):
    return MANAGED_INDEX + '\n\n' + '\n'.join(lines).rstrip() + '\n'


def table_text(text):
    return ' '.join(text.split()).replace('|', r'\|')


def report_links(folder):
    return f'[Markdown]({folder}/report.md) · [PDF]({folder}/report.pdf)'


def home_index(by_direction):
    lines = ['# Papers Daily', '',
             '每日论文精读。可以先看开篇速读，再按需查阅方法、公式、原图和实验。', '',
             '## 各方向最新一期', '',
             '| 方向 | 最新日期 | 主题 | 阅读 | 历史 |',
             '| --- | --- | --- | --- | --- |']
    for direction, reports in sorted(by_direction.items()):
        item, folder = reports[0]
        name = table_text(DIRECTION_NAMES.get(direction, direction))
        lines.append(
            f'| [{name}]({direction}/README.md) | {item["date"]} | {table_text(item["topic"])} '
            f'| {report_links(folder.as_posix())} | [按月浏览]({direction}/archive/README.md) |'
        )
    lines += ['', f'点方向名称查看最近 {RECENT_REPORTS} 期。历年日报和每篇论文的标题都可在对应方向的历史月份中找到。', '',
              '[提交规范](CONTRIBUTING.md) · [运行与日程](AUTOMATION.md) · [公式排版](scripts/MATH.md)']
    return markdown_document(lines)


def direction_index(direction, reports):
    latest_month = reports[0][0]['date'][:7]
    lines = direction_intro(direction)
    lines += ['[仓库首页](../README.md) · [全部历史月份](archive/README.md) '
              f'· [最新月份 {latest_month}](archive/{latest_month}.md)', '',
              f'## 最近 {RECENT_REPORTS} 期', '',
              '| 日期 | 主题 | 篇数 | 阅读 |', '| --- | --- | ---: | --- |']
    for item, _ in reports[:RECENT_REPORTS]:
        lines.append(f'| {item["date"]} | {table_text(item["topic"])} '
                     f'| {len(item["sources"])} | {report_links(item["date"])} |')
    return markdown_document(lines)


def archive_indexes(direction, reports):
    by_month = defaultdict(list)
    for item, _ in reports:
        by_month[item['date'][:7]].append(item)
    by_year = defaultdict(list)
    indexes = {}
    name = DIRECTION_NAMES.get(direction, direction)
    for month, month_reports in sorted(by_month.items(), reverse=True):
        by_year[month[:4]].append(month)
        lines = [f'# {name} · {month}', '',
                 '[仓库首页](../../README.md) · [方向首页](../README.md) · [全部历史月份](README.md)', '']
        for item in month_reports:
            lines += [f'## {item["date"]} · {table_text(item["topic"])}', '',
                      f'{report_links("../" + item["date"])} · {len(item["sources"])} 篇', '']
            for number, source in enumerate(item['sources'], 1):
                title = ' '.join(source['title'].split()).replace('\\', '\\\\')
                title = title.replace('[', r'\[').replace(']', r'\]')
                lines.append(f'{number}. [{title}](<{source["url"]}>) · {source["published"]}')
            if not item['sources']:
                lines.append(item.get('shortfall_reason') or '本期收录 0 篇。')
            lines.append('')
        indexes[Path(direction, 'archive', month + '.md')] = markdown_document(lines)

    lines = [f'# {name} · 历史归档', '',
             '[仓库首页](../../README.md) · [方向首页](../README.md)', '',
             '选择月份查看每期主题、论文标题、原文和精读。', '',
             '| 年份 | 月份 |', '| --- | --- |']
    for year, months in by_year.items():
        links = ' · '.join(f'[{month[5:]} 月]({month}.md)' for month in months)
        lines.append(f'| {year} | {links} |')
    indexes[Path(direction, 'archive', 'README.md')] = markdown_document(lines)
    return indexes


def update(root=ROOT, remote_files=None, *, check=False):
    remote_files = remote_files or set()
    by_direction, seen, records = defaultdict(list), {}, []
    for path in sorted(root.glob('*/*/manifest.json'), reverse=True):
        item = validate_manifest(json.loads(path.read_text(encoding='utf-8')), path)
        folder = path.parent.relative_to(root)
        for source in item['sources']:
            keys = aliases(source)
            for key in keys:
                if key in seen:
                    raise ValueError(f'Duplicate {key}: {path}; already in {seen[key]}')
            for key in keys:
                seen[key] = str(folder)
            records.append({**source, 'folder': str(folder), 'aliases': keys})
        for filename in ('report.md', 'report.pdf'):
            if not (path.parent / filename).is_file() and str(folder / filename) not in remote_files:
                raise ValueError(f'Missing {folder / filename}')
        by_direction[item['direction']].append((item, folder))

    indexes = {
        Path('README.md'): home_index(by_direction),
        Path('sources.json'): json.dumps(
            {'schema_version': 2, 'sources': records, 'aliases': seen},
            ensure_ascii=False, indent=2
        ) + '\n',
    }
    for direction, reports in sorted(by_direction.items()):
        indexes[Path(direction, 'README.md')] = direction_index(direction, reports)
        indexes.update(archive_indexes(direction, reports))

    changed = []
    for relative, content in indexes.items():
        path = root / relative
        if path.is_file() and path.read_text(encoding='utf-8') == content:
            continue
        changed.append(relative)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    for path in sorted(root.glob('*/archive/*.md')):
        relative = path.relative_to(root)
        if relative in indexes or not path.read_text(encoding='utf-8').startswith(MANAGED_INDEX):
            continue
        changed.append(relative)
        if not check:
            path.unlink()

    if check and changed:
        names = '\n'.join(str(path) for path in changed)
        raise SystemExit(f'Run python3 scripts/update_index.py to refresh:\n{names}')
    count = sum(map(len, by_direction.values()))
    print(f'Validated {count} reports, {len(records)} unique sources, {len(seen)} aliases')
    if changed:
        print('Refreshed indexes:')
        for path in changed:
            print(f'  {path}')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Verify generated files without writing them')
    parser.add_argument('--remote-tree', type=Path, help='GitHub recursive tree JSON for unchanged remote files in a sparse cloud workspace')
    args = parser.parse_args()
    remote = set()
    if args.remote_tree:
        inventory = json.loads(args.remote_tree.read_text(encoding='utf-8'))
        if inventory.get('truncated'):
            raise ValueError('Remote inventory is truncated; fetch the complete tree')
        remote = {e['path'] for e in inventory['tree'] if e['type'] == 'blob' and e.get('sha') and e.get('size', 0) > 0}
    update(remote_files=remote, check=args.check)
